"""Markdown governance report for one stored screening.

The text is a record of what the platform stored. It is not a compliance
certificate and it does not replace the reviewer's decision.
"""

import hashlib
from datetime import date, datetime


def render_governance_report(
    *,
    system_name: str,
    snapshot_version: int,
    purpose: str | None,
    assessment_id: int,
    assessment_status: str,
    rule_set_version: str,
    celex: str,
    content_sha256: str | None,
    assessed_on: date | None,
    notice: str,
    findings: list[dict],
    controls: list[dict],
    remediations: list[dict],
    decision: dict | None,
    report_version: int,
    generated_by: str,
    generated_at: datetime,
) -> str:
    """Build the markdown body for one report version."""
    lines = [
        f"# Governance report — {system_name}",
        "",
        notice,
        "",
        "This report records a decision-support screening and the governance actions stored with it. "
        "It does not certify legal compliance.",
        "",
        "## System",
        "",
        f"- Name: {system_name}",
        f"- Fact snapshot: {snapshot_version}",
        f"- Intended purpose: {purpose or 'Not recorded'}",
        "",
        "## Screening",
        "",
        f"- Assessment: {assessment_id}",
        f"- Status: {assessment_status}",
        f"- Rule set: {rule_set_version}",
        f"- Act: {celex}",
        f"- Act text: {content_sha256 or 'Not linked'}",
        f"- Assessment date: {assessed_on.isoformat() if assessed_on else 'Not recorded'}",
        "",
        "## Findings",
        "",
    ]
    if not findings:
        lines.append("No findings were stored.")
        lines.append("")
    for finding in findings:
        citations = ", ".join(finding["citations"]) or "No citation"
        lines.extend(
            [
                f"### {finding['rule_id']} — {finding['outcome']}",
                "",
                finding["explanation"],
                "",
                f"Citations: {citations}",
                "",
            ]
        )
    lines.extend(["## Controls", ""])
    if not controls:
        lines.append("No controls were linked to the findings.")
        lines.append("")
    for control in controls:
        note = f" — {control['notes']}" if control.get("notes") else ""
        lines.append(f"- {control['control_id']}: {control['title']} ({control['status']}){note}")
    lines.extend(["", "## Remediation", ""])
    if not remediations:
        lines.append("No remediation actions are stored.")
        lines.append("")
    for action in remediations:
        due = action["due_on"] or "no due date"
        lines.append(
            f"- {action['title']} — {action['status']}, owner {action['owner']}, due {due}"
        )
        for evidence in action["evidence"]:
            lines.append(f"  - Evidence ({evidence['review_status']}): {evidence['note']}")
    lines.extend(["", "## Review", ""])
    if decision is None:
        lines.append("No reviewer decision is stored for this screening.")
    else:
        lines.extend(
            [
                f"- Decision: {decision['decision']}",
                f"- Reviewer: {decision['reviewer_name']}",
                f"- Rationale: {decision['rationale']}",
            ]
        )
    lines.extend(
        [
            "",
            "## Report version",
            "",
            f"- Version: {report_version}",
            f"- Generated by: {generated_by}",
            f"- Generated at: {generated_at.isoformat()}",
            "",
        ]
    )
    return "\n".join(lines)


def report_sha256(markdown: str) -> str:
    """Digest the stored report bytes so a later version can be compared."""
    return hashlib.sha256(markdown.encode("utf-8")).hexdigest()
